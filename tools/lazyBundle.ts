import { mkdirSync, rmSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';

/**
 * Bundled data that the app reads one item at a time.
 *
 * Every item is its own minified JSON file, and one generated module lists
 * them: a small summary the app can use straight away, and a loader that reads
 * the item's file only when called. Metro turns each file into its own module,
 * and a module is not evaluated until something requires it — so a library of
 * tens of megabytes costs the size of its summaries at launch, not its size.
 * One big JSON file would be parsed whole the first time any item was wanted.
 */
export interface LazyBundle {
  /** Folder for the item files, e.g. `src/scores/chords`. */
  dir: string;
  /** The generated catalogue module. */
  catalogFile: string;
  /** Name the catalogue module exports. */
  exportName: string;
  /** TypeScript for the summary type's import, e.g. `import type { X } from '@domain';`. */
  summaryImport: string;
  summaryType: string;
  /** What the catalogue says wrote it, for the file header. */
  writtenBy: string;
}

export interface LazyBundleItem { id: string; summary: object; data: object }
export interface LazyBundleReport { count: number; bytes: number }

const SAFE_ID = /^[a-z0-9]+(?:-[a-z0-9]+)*$/;

function catalogSource(bundle: LazyBundle, items: readonly LazyBundleItem[]): string {
  const folder = bundle.dir.split('/').at(-1);
  const rows = items.map(({ id, summary }) => `  [${JSON.stringify(summary)}, () => require('./${folder}/${id}.json')],`);
  return `${bundle.summaryImport}

/**
 * Every bundled item: its summary, and a loader that reads the item's own JSON
 * file only when called. Metro needs each path written out in full to bundle
 * the file as its own module. Generated by ${bundle.writtenBy} — do not edit
 * by hand.
 */
export const ${bundle.exportName}: readonly (readonly [${bundle.summaryType}, () => unknown])[] = [
${rows.join('\n')}
];
`;
}

/** Replaces the bundle with exactly these items. */
export function writeLazyBundle(bundle: LazyBundle, items: readonly LazyBundleItem[]): LazyBundleReport {
  const unsafe = items.find(({ id }) => !SAFE_ID.test(id));
  if (unsafe) throw new Error(`"${unsafe.id}" cannot be a file name in ${bundle.dir}.`);
  const duplicate = items.find(({ id }, index) => items.findIndex((other) => other.id === id) !== index);
  if (duplicate) throw new Error(`"${duplicate.id}" appears twice in ${bundle.dir}.`);
  rmSync(bundle.dir, { recursive: true, force: true });
  mkdirSync(bundle.dir, { recursive: true });
  let bytes = 0;
  for (const { id, data } of items) {
    const json = JSON.stringify(data);
    bytes += json.length;
    writeFileSync(join(bundle.dir, `${id}.json`), json);
  }
  writeFileSync(bundle.catalogFile, catalogSource(bundle, items));
  return { count: items.length, bytes };
}
